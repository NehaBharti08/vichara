def requirements() -> str:
    """Runtime dependencies, read from pyproject rather than duplicated.

    A hand-maintained requirements.txt beside a pyproject is two sources of
    truth that drift silently, and the Space is exactly where that drift
    surfaces as an import error nobody sees until a reviewer clicks the link.
    """
    with (ROOT / "pyproject.toml").open("rb") as handle:
        deps = tomllib.load(handle)["project"]["dependencies"]

    # The Space image installs its own Gradio and will not be argued with:
    #
    #   pip install -r requirements.txt "torch<=2.13.0" \\
    #       gradio[oauth,mcp]==6.27.0 spaces==0.51.3
    #
    # pyproject pins gradio>=5.0,<6.0, so shipping that line leaves the two
    # constraints unsatisfiable and the build dies on a resolver conflict that
    # has nothing to do with this project. Dropping it lets the platform win,
    # which is the only outcome on offer.
    #
    # Safe because the two Gradio 6 breakages this UI had are already fixed:
    # the Blocks `css=` parameter, now a static <style> element, and the
    # gr.HTML `padding` default, now passed explicitly. Both surfaced as
    # deprecation warnings under Gradio 5 and were cleared then.
    deps = [d for d in deps if not d.lower().startswith("gradio")]

    header = (
        "# Generated by scripts/deploy_live_space.py from pyproject.toml.\n"
        "# gradio is deliberately absent: the Space image pins its own version\n"
        "# and a second constraint here only creates a resolver conflict.\n"
    )
    return header + "\n".join(sorted(deps)) + "\n"


def stage(into: Path) -> None:
    for source, target in PAYLOAD:
        src = ROOT / source
        dst = into / target
        dst.parent.mkdir(parents=True, exist_ok=True)
        if src.is_dir():
            shutil.copytree(src, dst, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
        else:
            shutil.copy2(src, dst)
    (into / "app.py").write_text(SPACE_APP, encoding="utf-8")
    (into / "requirements.txt").write_text(requirements(), encoding="utf-8")
    (into / "README.md").write_text(SPACE_README, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-id", required=True)
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Stage the payload and list it without uploading.",
    )
    args = parser.parse_args()

    api = HfApi()
    with tempfile.TemporaryDirectory() as tmp:
        staged = Path(tmp)
        stage(staged)

        files = sorted(p.relative_to(staged).as_posix() for p in staged.rglob("*") if p.is_file())
        total = sum(p.stat().st_size for p in staged.rglob("*") if p.is_file())
        print(f"{len(files)} files, {total / 1024:.0f} KB")
        for name in files[:12]:
            print(f"  {name}")
        if len(files) > 12:
            print(f"  ... and {len(files) - 12} more")

        # An allowlist by construction: only PAYLOAD is copied, so a .env or a
        # trajectory log cannot reach a public Space by being in the repo.
        leaked = [f for f in files if f.endswith((".env", ".jsonl.gz")) or "secret" in f.lower()]
        if leaked:
            print(f"refusing to upload, unexpected files: {leaked}", file=sys.stderr)
            return 1

        if args.dry_run:
            print("dry run, nothing uploaded")
            return 0

        api.upload_folder(
            repo_id=args.repo_id,
            repo_type="space",
            folder_path=str(staged),
            commit_message="Deploy the interactive agent",
        )

    print(f"uploaded: https://huggingface.co/spaces/{args.repo_id}")
    print("set GOOGLE_API_KEY in the Space settings, or via add_space_secret, before it will run")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
