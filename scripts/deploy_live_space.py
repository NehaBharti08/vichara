"""Deploy the *interactive* agent to a Hugging Face Gradio Space.

    uv run python scripts/deploy_live_space.py --repo-id nehabharti0802/vichara-live

This is the sibling of deploy_space.py, which publishes the static
recorded-trajectory viewer. Both exist because Hugging Face prices them
differently, and the difference is not the one the pricing page suggests:

    cpu-basic + gradio  ->  402 Payment Required, "requires a PRO subscription"
    zero-a10g  + gradio ->  created, no subscription

The 402 names cpu-basic specifically. ZeroGPU is available to free accounts, so
the live demo runs there. Nothing in this agent touches a GPU -- every model
call goes to the Gemini API -- but ZeroGPU is the tier that will host a Gradio
app for nothing, so that is the tier it uses.

What the Space does NOT get is Node, and therefore not the Pyodide sandbox. A
Gradio Space installs Python requirements and nothing else. That is a supported
degradation rather than a broken deploy: the registry drops `run_python` from
the capability set, the system prompt tells the agent it can no longer execute
code, and the trajectory records the reduced profile. Retrieval, web search and
file tools are unaffected.
"""

